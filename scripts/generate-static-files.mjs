// Postbuild step (kickoff Prompt 3 items 1-2): generates dist/sitemap.xml,
// dist/robots.txt, and dist/_redirects (Cloudflare Pages format) from
// docs/sitemap.json — the single source of truth for both the page
// inventory and the redirect map (topical-map.md §12.1), so nothing here
// is hand-copied from the spec doc.
import fs from "node:fs";
import path from "node:path";

const SITE = "https://boxhauls.com";
const cwd = process.cwd();
const distDir = path.resolve(cwd, "dist");

const sitemapData = JSON.parse(fs.readFileSync(path.resolve(cwd, "docs/sitemap.json"), "utf-8"));
const placeholders = JSON.parse(fs.readFileSync(path.resolve(cwd, "docs/placeholders.json"), "utf-8"));

function flattenPlaceholders(data) {
  const flat = {};
  for (const [key, value] of Object.entries(data)) {
    if (key.startsWith("_")) continue;
    if (typeof value === "string") flat[key] = value;
    else if (value && typeof value === "object" && !Array.isArray(value)) {
      for (const [k, v] of Object.entries(value)) {
        if (typeof v === "string") flat[`${key}.${k}`] = v;
      }
    }
  }
  return flat;
}

const flatPlaceholders = flattenPlaceholders(placeholders);

function substitute(text) {
  return text.replace(/\{\{([A-Za-z0-9_.-]+)\}\}/g, (_match, key) => {
    const raw = flatPlaceholders[key];
    if (raw === undefined || raw.startsWith("TODO")) {
      throw new Error(`generate-static-files: unresolved placeholder {{${key}}} in "${text}" — same rule as src/lib/placeholders.ts.`);
    }
    return raw;
  });
}

// ---------------------------------------------------------------- sitemap.xml
// Every page in sitemap.json is indexable — /auth, /account, /embed/,
// /api/, /book/ are app-only routes with no entry in the pages array.
const buildDate = new Date().toISOString().slice(0, 10);

const urlEntries = sitemapData.pages
  .map((p) => `  <url>\n    <loc>${SITE}${substitute(p.url)}</loc>\n    <lastmod>${buildDate}</lastmod>\n  </url>`)
  .join("\n");

const sitemapXml = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urlEntries}\n</urlset>\n`;

fs.writeFileSync(path.join(distDir, "sitemap.xml"), sitemapXml);

// ----------------------------------------------------------------- robots.txt
const robotsTxt = `User-agent: *
Allow: /
Disallow: /auth
Disallow: /account
Disallow: /embed/
Disallow: /api/
Disallow: /book/

Sitemap: ${SITE}/sitemap.xml
`;

fs.writeFileSync(path.join(distDir, "robots.txt"), robotsTxt);

// ----------------------------------------------------------------- _redirects
// "/guides/  (map each post to its rewritten guide; else /guides/)" ->
// { path: "/guides/", note: "map each post..." }. Falls back to treating
// the whole string as the path when there's no trailing "(...)" note.
function extractPathAndNote(raw) {
  const match = raw.match(/^([^\s(]+)\s*(?:\((.+)\))?\s*$/);
  if (!match) return { path: raw.trim(), note: null };
  return { path: match[1].trim(), note: match[2] ? match[2].trim() : null };
}

function isRealPath(p) {
  return p.startsWith("/") || p.startsWith("http");
}

const redirectLines = ["# Generated by scripts/generate-static-files.mjs from docs/sitemap.json's redirects array.", "# Do not hand-edit — edit build_map.py's REDIRECTS, run `npm run map`, rebuild.", ""];
const skipped = [];

for (const { from, to } of sitemapData.redirects) {
  const fromParsed = extractPathAndNote(from);
  const toParsed = extractPathAndNote(to);

  if (!isRealPath(toParsed.path)) {
    // Instructional entry (e.g. "keep on new domain, noindex") rather than
    // an actual redirect — that path stays live and is handled via
    // robots.txt Disallow instead.
    skipped.push(`${from} -> ${to}`);
    continue;
  }

  const fromPath = substitute(fromParsed.path);
  const toPath = substitute(toParsed.path);
  if (fromPath === toPath) continue; // no-op, e.g. "/" -> "/"

  const note = fromParsed.note || toParsed.note;
  if (note) redirectLines.push(`# ${note}`);
  redirectLines.push(`${fromPath} ${toPath} 301`);
}

// www -> apex is NOT written here: Cloudflare Pages' _redirects format only
// accepts relative-path sources (no hostname), so a cross-host rule like
// "https://www.boxhauls.com/* -> https://boxhauls.com/:splat" fails Cloudflare's
// _redirects validation at deploy time ("Only relative URLs are allowed").
// That redirect has to be a Cloudflare Redirect Rule at the zone level instead,
// configured once both boxhauls.com and www.boxhauls.com are added as custom
// domains on the Pages project — see docs/LAUNCH.md §1.

fs.writeFileSync(path.join(distDir, "_redirects"), redirectLines.join("\n") + "\n");

console.log(`sitemap.xml: ${sitemapData.pages.length} urls`);
console.log(`_redirects: ${redirectLines.filter((l) => / 301$/.test(l)).length} rules (${skipped.length} instructional entries skipped, handled via robots.txt instead):`);
for (const s of skipped) console.log(`  - ${s}`);
